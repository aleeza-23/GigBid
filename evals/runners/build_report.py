def demote(text: str, levels: int = 2) -> str:
    """Push every heading down, so an included file sits under a report section."""
    out = []
    for line in text.splitlines():
        if re.match(r"^#{1,5} ", line):
            line = "#" * levels + line
        out.append(line)
    return "\n".join(out).strip()


def doc(name: str) -> str:
    return demote((REPO / "docs" / name).read_text(encoding="utf-8"))


def section_of(path: Path, heading: str, levels: int = 2) -> str:
    """One `## heading` block out of a larger markdown file."""
    text = path.read_text(encoding="utf-8")
    start = text.index(heading)
    nxt = text.find("\n## ", start + len(heading))
    return demote(text[start : nxt if nxt != -1 else len(text)], levels)


